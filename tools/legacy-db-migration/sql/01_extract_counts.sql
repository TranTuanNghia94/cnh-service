-- Read-only baseline counts on LEGACY database.
-- Run with: psql "$LEGACY_DATABASE_URL" -f sql/01_extract_counts.sql

SELECT 'core.SYS_USER' AS table_name, COUNT(*) AS row_count FROM core."SYS_USER"
UNION ALL SELECT 'core.SYS_ROLE', COUNT(*) FROM core."SYS_ROLE"
UNION ALL SELECT 'ies.VEN_VENDOR', COUNT(*) FROM ies."VEN_VENDOR"
UNION ALL SELECT 'ies.CUS_CUSTOMER', COUNT(*) FROM ies."CUS_CUSTOMER"
UNION ALL SELECT 'ies.CUS_CUSTOMER_CONTACT', COUNT(*) FROM ies."CUS_CUSTOMER_CONTACT"
UNION ALL SELECT 'ies.PRO_PRODUCT_CAT', COUNT(*) FROM ies."PRO_PRODUCT_CAT"
UNION ALL SELECT 'ies.PRO_PRODUCT', COUNT(*) FROM ies."PRO_PRODUCT"
UNION ALL SELECT 'ies.ORD_ORDER', COUNT(*) FROM ies."ORD_ORDER"
UNION ALL SELECT 'ies.ORD_ORDER_LINE', COUNT(*) FROM ies."ORD_ORDER_LINE"
UNION ALL SELECT 'ies.PO_PURCHASE_ORDER', COUNT(*) FROM ies."PO_PURCHASE_ORDER"
UNION ALL SELECT 'ies.PO_PURCHASE_ORDER_LINE', COUNT(*) FROM ies."PO_PURCHASE_ORDER_LINE"
UNION ALL SELECT 'ies.PAY_PAYMENT', COUNT(*) FROM ies."PAY_PAYMENT"
UNION ALL SELECT 'ies.PAY_PAYMENT_LINE', COUNT(*) FROM ies."PAY_PAYMENT_LINE"
UNION ALL SELECT 'ies.IMPORT_REQUEST', COUNT(*) FROM ies."IMPORT_REQUEST"
UNION ALL SELECT 'ies.EXPORT_REQUEST', COUNT(*) FROM ies."EXPORT_REQUEST"
UNION ALL SELECT 'ies.INVENTORY', COUNT(*) FROM ies."INVENTORY"
ORDER BY 1;
